const fs = require('node:fs');
const path = require('node:path');
const { transformSync } = require('esbuild');

const root = path.resolve(__dirname, '..');
// Syntax only: missing runtime APIs must still have an explicit implementation
// or fallback. Chrome 57 also retains native async/await without a runtime shim.
const TARGET = 'chrome57';
const CLIENT_PATH = path.join(root, 'public', 'client.js');

function compileClient(domainSource, appSource) {
  const result = transformSync(`${domainSource}\n;\n${appSource}`, {
    target: TARGET,
    loader: 'js',
    charset: 'utf8',
    legalComments: 'none',
    sourcefile: 'client.js',
  });
  return `// Generated by npm run build:web. Edit public/app.js or shared/domain.js.\n${result.code}`;
}

function buildWebAssets() {
  const output = compileClient(
    fs.readFileSync(path.join(root, 'shared', 'domain.js'), 'utf8'),
    fs.readFileSync(path.join(root, 'public', 'app.js'), 'utf8'),
  );
  if (!fs.existsSync(CLIENT_PATH) || fs.readFileSync(CLIENT_PATH, 'utf8') !== output) {
    fs.writeFileSync(CLIENT_PATH, output);
  }
  return output;
}

if (require.main === module) {
  buildWebAssets();
  console.log(`Browser client built for ${TARGET}`);
}

module.exports = { buildWebAssets, compileClient, TARGET, CLIENT_PATH };
